#!/usr/bin/env bash
# =============================================================================
# 离线模型预置脚本
# -----------------------------------------------------------------------------
# 在有外网的机器上运行一次，把 Indra 模型缓存到本地目录，再拷到内网服务器。
# 内网服务器无外网，必须预置，否则服务启动时下载失败、健康检查永久 false。
#
# 用法：
#   ./prepare_models.sh  [输出目录，默认 ./models]
# =============================================================================
set -euo pipefail

OUT_DIR="${1:-./models}"
mkdir -p "$OUT_DIR"

# 模型落到 HF_HOME 下的 hub/ 子目录
export HF_HOME="$OUT_DIR"

python3 - <<'PY'
import os
import indra_ocr

# 触发一次加载，强制下载 + 缓存（datalab-to/indra-ocr，约 72MB）
conv = indra_ocr.load(mode="ocr")
print("模型已缓存到:", os.environ["HF_HOME"])
PY

echo
echo "======================================================"
echo " 模型预置完成，目录: $OUT_DIR"
echo " 将该目录整个拷到服务器，挂载为 /opt/models（只读）"
echo " 并在服务器设 HF_HUB_OFFLINE=1 禁止联网。"
echo "======================================================"
